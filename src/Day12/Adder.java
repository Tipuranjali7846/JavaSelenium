package Day12;

public class Adder {
	int x=10,y=20;	
	
	void sum() {
		System.out.println(x+y);
	}
	
	void sum(int a, int b) {
		System.out.println(a+b);
	}
	
	void sum(int a, double b) {
		System.out.println(a+b);
	}
	
	void sum(double a ,double b) {
		System.out.println(a+b);
	}
	
	void sum(double a, int b) {
		System.out.println(a+b);
	}
	
	
}
